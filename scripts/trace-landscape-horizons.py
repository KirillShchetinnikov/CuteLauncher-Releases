"""Trace code-native sky contours from the unchanged seasonal PNGs (requires Pillow)."""
from pathlib import Path
from PIL import Image
from statistics import median
from math import hypot

def simplify(points, tolerance=.65):
    if len(points)<3: return points
    x0,y0=points[0]; x1,y1=points[-1]
    length=hypot(x1-x0,y1-y0)
    distances=[abs((y1-y0)*(x-x0)-(x1-x0)*(y-y0))/length for x,y in points[1:-1]]
    maximum=max(distances,default=0)
    if maximum<=tolerance: return [points[0],points[-1]]
    pivot=distances.index(maximum)+1
    return simplify(points[:pivot+1],tolerance)[:-1]+simplify(points[pivot:],tolerance)

output=['// Generated by scripts/trace-landscape-horizons.py from the unchanged PNGs.',
    '// Source coordinates in pixels. Regenerate whenever a seasonal photograph changes.',
    'const landscapePhotoSize = (1672.0, 941.0);',
    'const landscapePhotoRidges = <String, List<(int, int)>>{']
for season,name in [('summer','valley'),('spring','spring'),('autumn','autumn'),('winter','winter')]:
    image=Image.open(Path('assets/landscapes')/(name+'.png')).convert('RGB')
    w,h=image.size
    assert (w,h)==(1672,941)
    pixels=image.load(); heights=[]
    for x in range(w):
        for y in range(int(h*.22),int(h*.52)):
            if sum(abs(pixels[x,y+2][i]-pixels[x,y-2][i]) for i in range(3))>28:
                heights.append(y); break
        else: raise ValueError(f'No sky boundary at {name}:{x}')
    heights=[round(median(heights[max(0,x-2):min(w,x+3)]))+1 for x in range(w)]
    points=simplify(list(enumerate(heights)))
    output.append(f"  '{season}': [")
    for i in range(0,len(points),6):
        output.append('    '+', '.join(f'({x}, {y})' for x,y in points[i:i+6])+',')
    output.append('  ],')
    print(season,len(points),'vertices')
output.append('};')
Path('lib/landscape_horizon_data.dart').write_text('// dart format off\n'+'\n'.join(output)+'\n// dart format on\n',encoding='utf-8')
